import json, re
from datetime import datetime, timezone
from .config import settings
from .seed_data import POLICIES

ACTIONS = {"Auto-Resolve", "Route to Team", "Flag for Review"}
def deterministic_decision(request: dict, policies: list[dict]) -> dict:
    text = (request.get("message","") + " " + request.get("summary","")).lower()
    def has(*terms): return any(t in text for t in terms)
    matched, category, action, confidence, reasoning = [], "General IT Request", "Flag for Review", 0.35, "The request is too vague to safely determine a policy or action. Ask the employee for clarification."
    if has("phishing","malware","unauthorized access","suspicious email"):
        matched=["KB-09"]; category="Security Incident"; action="Flag for Review"; confidence=.99
        reasoning="The request may involve a security incident. KB-09 says suspected phishing, malware, or unauthorized access must be reported to Security immediately and not forwarded to other employees."
    elif has("laptop","screen flicker","hardware failure","won’t turn on","wont turn on"):
        matched=["KB-03","AM-01"]; category="IT Hardware"; action="Flag for Review"; confidence=.62
        reasoning="KB-03 allows replacement after 3 years or earlier for verified hardware failure. The Asset Management Policy Extract specifies a 4-year refresh cycle and Finance sign-off for early replacement. These sources conflict; a human reviewer should verify device history and approvals."
    elif has("guest wi-fi","guest wifi","wi-fi access","wifi access"):
        matched=["KB-07"]; category="Network Access"; action="Auto-Resolve"; confidence=.94
        reasoning="KB-07 says guest Wi-Fi credentials are valid for 24 hours and can be generated by any employee at the front-desk kiosk. No IT ticket is required."
    elif has("locked out","password","reset"):
        matched=["KB-01"]; category="Account Access"; action="Route to Team" if has("6 times","six times","locked out","lockout") else "Auto-Resolve"; confidence=.91
        reasoning="KB-01 allows self-service password reset. After more than five failed attempts, IT must manually unlock the account."
    elif has("vpn"):
        matched=["KB-02"]; category="VPN Access"; action="Route to Team" if has("contractor") else "Auto-Resolve"; confidence=.91
        reasoning="KB-02 says full-time employees receive VPN access automatically, contractors need manager approval, and credentials expire every 90 days and must be renewed by the employee."
    elif has("software","browser extension","install"):
        matched=["KB-04"]; category="Software Request"; action="Route to Team"; confidence=.93
        reasoning="KB-04 says standard catalog software can be self-installed; non-catalog software requires IT Security review taking 3–5 business days."
    elif has("printer","paper jam"):
        matched=["KB-05"]; category="Hardware Support"; action="Route to Team"; confidence=.82
        reasoning="KB-05 instructs employees to check the printer queue and restart the print spooler. If the issue persists, log a ticket with the printer asset tag."
    elif has("mailbox","email quota","can't send emails","can’t send emails"):
        matched=["KB-06"]; category="Email Support"; action="Auto-Resolve"; confidence=.86
        reasoning="KB-06 sets the default mailbox quota at 25GB. Employees should archive old mail; increases above 25GB need manager approval and are capped at 50GB."
    elif has("expense tool","expense management"):
        matched=["KB-08"]; category="Application Support"; action="Route to Team"; confidence=.84
        reasoning="KB-08 says Finance grants expense-tool access. IT can assist with login or technical issues only if an account already exists."
    elif has("monitor","home office","working from home"):
        matched=["KB-10","AM-01"]; category="Equipment Request"; action="Route to Team"; confidence=.88
        reasoning="KB-10 eligibility requires remote work more than 3 days per week, manager sign-off, and Finance processing. IT handles shipping only after approval."
    if confidence < .65: action = "Flag for Review"
    policy_map={p["id"]:p for p in policies}
    return {"category":category,"matched_policy":[{"id":pid,"title":policy_map.get(pid,{}).get("title",pid)} for pid in matched],"action":action,"confidence":round(confidence,2),"reasoning":reasoning,"needs_human_review":action=="Flag for Review","provider":"rules_fallback"}
async def analyze_request(request: dict, policies: list[dict]) -> dict:
    if not settings.openai_api_key:
        return deterministic_decision(request, policies)
    try:
        from openai import AsyncOpenAI
        client=AsyncOpenAI(api_key=settings.openai_api_key)
        payload={"request":{"id":request.get("id"),"employee":request.get("employee"),"message":request.get("message")},"policies":[{"id":p["id"],"title":p["title"],"body":p["body"]} for p in policies]}
        system="""You are Veridian Corp's internal IT request triage agent. Use ONLY the supplied policies; never invent policy. Return only JSON with keys category (string), matched_policy (array of objects with id,title), action (one of Auto-Resolve, Route to Team, Flag for Review), confidence (number 0 to 1), reasoning (string), needs_human_review (boolean). Flag policy conflicts, vague requests, security incidents, unsupported access grants, and low confidence (<0.65) for human review. KB-03's 3-year laptop replacement rule conflicts with AM-01's 4-year cycle; do not silently reconcile it. Do not claim to have performed actions."""
        response=await client.chat.completions.create(model=settings.openai_model,temperature=0,response_format={"type":"json_object"},messages=[{"role":"system","content":system},{"role":"user","content":json.dumps(payload,ensure_ascii=False)}])
        data=json.loads(response.choices[0].message.content)
        if data.get("action") not in ACTIONS: raise ValueError("Invalid action")
        conf=float(data.get("confidence",0))
        if not 0<=conf<=1: raise ValueError("Invalid confidence")
        if conf < .65 or data.get("needs_human_review") or request.get("id")=="REQ-01" or request.get("id")=="REQ-15":
            data["action"]="Flag for Review"; data["needs_human_review"]=True
        valid_ids={p["id"] for p in policies}
        data["matched_policy"]=[p for p in data.get("matched_policy",[]) if p.get("id") in valid_ids]
        data["confidence"]=round(conf,2); data["provider"]="openai"
        return data
    except Exception as exc:
        fallback=deterministic_decision(request,policies)
        fallback["provider"]="rules_fallback"
        fallback["llm_warning"]="LLM unavailable or returned invalid output; used policy-grounded fallback."
        return fallback
